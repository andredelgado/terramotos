// Build hosting/font.mjs: the letter shapes the Worker uses to write on earthquake preview images.
//
// The Worker draws those images itself and has no font engine, so each character is drawn once
// here, in a browser, and stored as a small greyscale picture. The font is Inter (SIL Open Font
// License 1.1), from the @fontsource/inter dev dependency.
//
// Usage: node tools/build_font.mjs      (only needed when the sizes or characters below change)
import { chromium } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const FILES = path.join(ROOT, 'node_modules/@fontsource/inter/files');
// every character of the catalogue's place names and the page's dates, and room for story titles
const TEXT = ' !"#%&\'()*+,-./0123456789:;?ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz' +
  'ÀÁÂÃÇÉÊÍÓÔÕÚàáâãçéêíñóôõúü°·–—’…';
const FACES = {
  big: { size: 176, weight: 700, chars: ' M0123456789,.–' },
  text: { size: 46, weight: 600, chars: TEXT },
  small: { size: 30, weight: 400, chars: TEXT },
};

const browser = await chromium.launch();
const page = await browser.newPage();
const out = {};
for (const [name, face] of Object.entries(FACES)) {
  const font = fs.readFileSync(path.join(FILES, `inter-latin-${face.weight}-normal.woff2`)).toString('base64');
  out[name] = await page.evaluate(async ({ font, face }) => {
    const family = 'Atlas' + face.weight;
    const loaded = await new FontFace(family, `url(data:font/woff2;base64,${font})`, { weight: String(face.weight) }).load();
    document.fonts.add(loaded);
    const canvas = document.createElement('canvas'), pad = 8;
    canvas.width = canvas.height = face.size * 2;
    const ctx = canvas.getContext('2d', { willReadFrequently: true });
    const glyphs = {}, nibbles = [];
    for (const ch of new Set(face.chars)) {
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      ctx.font = `${face.weight} ${face.size}px ${family}`;
      ctx.fillStyle = '#000';
      const m = ctx.measureText(ch), x0 = pad + Math.ceil(m.actualBoundingBoxLeft), y0 = pad + Math.ceil(m.actualBoundingBoxAscent);
      ctx.fillText(ch, x0, y0);
      const img = ctx.getImageData(0, 0, canvas.width, canvas.height).data;
      let l = canvas.width, r = -1, t = canvas.height, b = -1;
      for (let y = 0; y < canvas.height; y++) for (let x = 0; x < canvas.width; x++) {
        if (img[(y * canvas.width + x) * 4 + 3] >> 4) { l = Math.min(l, x); r = Math.max(r, x); t = Math.min(t, y); b = Math.max(b, y); }
      }
      const advance = Math.round(m.width * 100) / 100;
      if (r < 0) { glyphs[ch] = [advance, 0, 0, 0, 0, 0]; continue; }
      // advance, left and top of the picture relative to the pen on the baseline, width, height, where its pixels start
      glyphs[ch] = [advance, l - x0, t - y0, r - l + 1, b - t + 1, nibbles.length];
      for (let y = t; y <= b; y++) for (let x = l; x <= r; x++) nibbles.push(img[(y * canvas.width + x) * 4 + 3] >> 4);
    }
    if (nibbles.length % 2) nibbles.push(0);
    let binary = '';
    for (let i = 0; i < nibbles.length; i += 2) binary += String.fromCharCode(nibbles[i] << 4 | nibbles[i + 1]);
    return { size: face.size, glyphs, data: btoa(binary) };
  }, { font, face });
}
await browser.close();

const body = `// Generated by tools/build_font.mjs from Inter (SIL Open Font License 1.1). Do not edit by hand.
// Each face: its size in pixels; per character [advance, left, top, width, height, start]; and
// the pictures themselves, 16 levels of grey, two pixels to a byte, in base64.
export const FONTS = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(ROOT, 'hosting/font.mjs'), body);
console.log(`hosting/font.mjs: ${Object.entries(out).map(([k, v]) => `${k} ${Object.keys(v.glyphs).length} characters`).join(', ')}, ${(body.length / 1024).toFixed(0)} KB`);
